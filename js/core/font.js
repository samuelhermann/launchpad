/* Police 5x7 (texte défilant) et chiffres 3x5 (scores statiques) pour la grille 8x8. */
(function (LP) {
  'use strict';
  const U = LP.U;

  // Chaque glyphe : 5 colonnes, bit 0 = ligne du haut.
  const G = {
    'A': [0x7C, 0x12, 0x11, 0x12, 0x7C], 'B': [0x7F, 0x49, 0x49, 0x49, 0x36],
    'C': [0x3E, 0x41, 0x41, 0x41, 0x22], 'D': [0x7F, 0x41, 0x41, 0x22, 0x1C],
    'E': [0x7F, 0x49, 0x49, 0x49, 0x41], 'F': [0x7F, 0x09, 0x09, 0x09, 0x01],
    'G': [0x3E, 0x41, 0x49, 0x49, 0x7A], 'H': [0x7F, 0x08, 0x08, 0x08, 0x7F],
    'I': [0x00, 0x41, 0x7F, 0x41, 0x00], 'J': [0x20, 0x40, 0x41, 0x3F, 0x01],
    'K': [0x7F, 0x08, 0x14, 0x22, 0x41], 'L': [0x7F, 0x40, 0x40, 0x40, 0x40],
    'M': [0x7F, 0x02, 0x0C, 0x02, 0x7F], 'N': [0x7F, 0x04, 0x08, 0x10, 0x7F],
    'O': [0x3E, 0x41, 0x41, 0x41, 0x3E], 'P': [0x7F, 0x09, 0x09, 0x09, 0x06],
    'Q': [0x3E, 0x41, 0x51, 0x21, 0x5E], 'R': [0x7F, 0x09, 0x19, 0x29, 0x46],
    'S': [0x46, 0x49, 0x49, 0x49, 0x31], 'T': [0x01, 0x01, 0x7F, 0x01, 0x01],
    'U': [0x3F, 0x40, 0x40, 0x40, 0x3F], 'V': [0x1F, 0x20, 0x40, 0x20, 0x1F],
    'W': [0x3F, 0x40, 0x38, 0x40, 0x3F], 'X': [0x63, 0x14, 0x08, 0x14, 0x63],
    'Y': [0x07, 0x08, 0x70, 0x08, 0x07], 'Z': [0x61, 0x51, 0x49, 0x45, 0x43],
    '0': [0x3E, 0x51, 0x49, 0x45, 0x3E], '1': [0x00, 0x42, 0x7F, 0x40, 0x00],
    '2': [0x42, 0x61, 0x51, 0x49, 0x46], '3': [0x21, 0x41, 0x45, 0x4B, 0x31],
    '4': [0x18, 0x14, 0x12, 0x7F, 0x10], '5': [0x27, 0x45, 0x45, 0x45, 0x39],
    '6': [0x3C, 0x4A, 0x49, 0x49, 0x30], '7': [0x01, 0x71, 0x09, 0x05, 0x03],
    '8': [0x36, 0x49, 0x49, 0x49, 0x36], '9': [0x06, 0x49, 0x49, 0x29, 0x1E],
    '!': [0x00, 0x00, 0x5F, 0x00, 0x00], '?': [0x02, 0x01, 0x51, 0x09, 0x06],
    '.': [0x00, 0x60, 0x60, 0x00, 0x00], ',': [0x00, 0x50, 0x30, 0x00, 0x00],
    ':': [0x00, 0x36, 0x36, 0x00, 0x00], '-': [0x08, 0x08, 0x08, 0x08, 0x08],
    '+': [0x08, 0x08, 0x3E, 0x08, 0x08], '=': [0x14, 0x14, 0x14, 0x14, 0x14],
    '/': [0x20, 0x10, 0x08, 0x04, 0x02], "'": [0x00, 0x00, 0x07, 0x00, 0x00],
    '*': [0x0C, 0x1E, 0x3C, 0x1E, 0x0C] /* cœur */
  };

  // Chiffres 3x5
  const D = [
    ['111', '101', '101', '101', '111'], ['010', '110', '010', '010', '111'],
    ['111', '001', '111', '100', '111'], ['111', '001', '111', '001', '111'],
    ['101', '101', '111', '001', '001'], ['111', '100', '111', '001', '111'],
    ['111', '100', '111', '101', '111'], ['111', '001', '010', '010', '010'],
    ['111', '101', '111', '101', '111'], ['111', '101', '111', '001', '111']
  ];

  function columns(text) {
    const cols = [];
    for (const ch of U.plain(text)) {
      if (ch === ' ') { cols.push(0, 0, 0); continue; }
      const g = G[ch] || G['?'];
      let s = 0, e = 4;
      while (s < 4 && g[s] === 0) s++;
      while (e > s && g[e] === 0) e--;
      for (let i = s; i <= e; i++) cols.push(g[i]);
      cols.push(0);
    }
    return cols;
  }

  class Scroller {
    constructor(text, color, opts) {
      opts = opts || {};
      this.cols = new Array(8).fill(0).concat(columns(text));
      this.pos = 0;
      this.speed = opts.speed || 11; // colonnes par seconde
      this.color = color || [255, 255, 255];
      this.loop = !!opts.loop;
      this.y = opts.y === undefined ? 1 : opts.y;
      this.done = false;
    }
    update(dt) {
      this.pos += dt * this.speed;
      if (this.pos > this.cols.length) {
        if (this.loop) this.pos = 0; else this.done = true;
      }
    }
    render(fb, t) {
      const off = Math.floor(this.pos);
      for (let x = 0; x < 8; x++) {
        const bits = this.cols[off + x];
        if (!bits) continue;
        for (let r = 0; r < 7; r++) {
          if ((bits >> r) & 1) {
            const c = typeof this.color === 'function' ? this.color(x, r + this.y, off + x, t) : this.color;
            fb.set(x, r + this.y, c);
          }
        }
      }
    }
  }

  function drawDigit(fb, d, ox, oy, color) {
    const g = D[d];
    for (let r = 0; r < 5; r++) for (let c = 0; c < 3; c++) if (g[r][c] === '1') fb.set(ox + c, oy + r, color);
  }

  /* Affiche un nombre 0..99 centré (3x5). */
  function digits(fb, n, color, oy) {
    n = Math.max(0, Math.floor(n)) % 100;
    oy = oy === undefined ? 1 : oy;
    if (n < 10) drawDigit(fb, n, 3, oy, color);
    else { drawDigit(fb, Math.floor(n / 10), 0, oy, color); drawDigit(fb, n % 10, 4, oy, color); }
  }

  LP.font = { columns, Scroller, digits, drawDigit, glyphs: G };
})(window.LP);
